async def _run_process(job_id: str, cmd: list, start_time: float):
    try:
        process = await asyncio.create_subprocess_exec(
            *cmd,
            stdout=asyncio.subprocess.PIPE,
            stderr=asyncio.subprocess.STDOUT,
            cwd=str(BASE_DIR),
            env={**os.environ, "PYTHONIOENCODING": "utf-8", "PYTHONUTF8": "1"}
        )
        jobs[job_id]["process"] = process

        while True:
            line_bytes = await process.stdout.readline()
            if not line_bytes:
                break
            text = line_bytes.decode("utf-8", errors="replace").rstrip()
            if not text.strip():
                continue

            event = _parse_log_line(text)
            event["raw"] = text
            job_events[job_id].append(event)

        await process.wait()
        success = process.returncode == 0
        if success:
            job_dir = OUTPUT_DIR / job_id
            job_dir.mkdir(parents=True, exist_ok=True)
            meta = {
                "job_id": job_id,
                "filename": jobs[job_id]["filename"],
                "created": time.time()
            }
            with open(job_dir / "metadata.json", "w", encoding="utf-8") as f:
                json.dump(meta, f)

        clips = _list_clips(job_id=job_id, newer_than=start_time - 5)
        job_events[job_id].append({
            "type": "done",
            "success": success,
            "clips": clips
        })
    except Exception as e:
        job_events[job_id].append({"type": "error", "message": str(e)})
    finally:
        job_done[job_id] = True

