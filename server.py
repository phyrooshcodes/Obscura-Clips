@app.websocket("/ws/{job_id}")
async def run_pipeline_ws(
    websocket: WebSocket,
    job_id:    str
):
    await websocket.accept()
    
    config = job_configs.get(job_id, {})
    model = config.get("model", "small")
    max_clips = int(config.get("max_clips", 10))
    language = config.get("language", "")
    music = config.get("music", "none")
    caption_style = config.get("caption_style", "kinetic_slide")
    font_preset = config.get("font_preset", "Montserrat-Black")
    font_name = config.get("font_name", "")
    font_size = int(config.get("font_size", 48))
    primary_color = config.get("primary_color", "#FFFFFF")
    outline_color = config.get("outline_color", "#000000")
    no_title = config.get("no_title", False)
    broll = config.get("broll", False)
    pexels_key = config.get("pexels_key", "")
    force_restart = config.get("force_restart", False)

    if job_id not in jobs:
        await websocket.send_json({"type": "error", "message": "Job not found."})
        await websocket.close()
        return

    job = jobs[job_id]
    start_time = job["start_time"]
    
    if force_restart or job_id not in job_events:
        job_events[job_id] = []
        job_done[job_id] = False
        
        job_events[job_id].append({"type": "start", "filename": job["filename"]})

        if music == "off": music = "none"
        job_dir = OUTPUT_DIR / job_id
        job_dir.mkdir(parents=True, exist_ok=True)
        
        python_exe = str(BASE_DIR / "venv" / "Scripts" / "python.exe")
        if not Path(python_exe).exists():
            python_exe = str(BASE_DIR / "venv" / "bin" / "python")
            if not Path(python_exe).exists():
                python_exe = sys.executable

        cmd = [
            python_exe,
            str(BASE_DIR / "local_clipping_pipeline.py"),
            "--input", job["path"],
            "--output-dir", str(job_dir),
            "--model", model,
            "--max-clips", str(max_clips),
            "--music", music,
            "--caption-style", caption_style,
            "--font-preset", font_preset,
            "--font-name", font_name,
            "--font-size", str(font_size),
            "--primary-color", primary_color,
            "--outline-color", outline_color,
        ]
        if no_title: cmd += ["--no-title"]
        if broll and pexels_key.strip(): cmd += ["--broll", "--pexels-key", pexels_key.strip()]
        if language.strip(): cmd += ["--language", language.strip()]

        asyncio.create_task(_run_process(job_id, cmd, start_time))

    try:
        last_index = 0
        while True:
            if last_index < len(job_events[job_id]):
                event = job_events[job_id][last_index]
                await websocket.send_json(event)
                last_index += 1
                if event.get("type") in ("done", "error"):
                    break
            elif job_done[job_id]:
                break
            else:
                await asyncio.sleep(0.5)
    except Exception as e:
        logger.error(f"WebSocket error in run_pipeline_ws for job {job_id}: {e}")
    finally:
        try:
            await websocket.close()
        except Exception:
            pass


# ─── Helpers ────────────────────────────────────────────────

def _parse_log_line(text: str) -> dict:
    """Convert a raw pipeline log line into a structured UI event."""

    # Main stage: "═══ STAGE 2/6 ─ ASR Transcription (CPU INT8) ═══"
    m = re.search(r"STAGE\s+(\d+)/6[^─\-]*[\-─]\s*(.+?)(?:\s*[═=]+\s*$|\s*$)", text)
    if m:
        return {"type": "stage", "stage": int(m.group(1)), "label": m.group(2).strip()}

    # Clip start: "═══ CLIP 1/5 ══"
    m = re.search(r"CLIP\s+(\d+)/(\d+)", text)
    if m:
        return {"type": "clip_start", "clip_num": int(m.group(1)), "total": int(m.group(2))}

    # Sub-stage: "[4/6] Face Tracking"
    m = re.search(r"\[(\d+)/6\]\s+(.+)", text)
    if m:
        return {"type": "substage", "substage": int(m.group(1)), "label": m.group(2).strip()}

    # Clip ready: "✅ Done → output/clip_01_..."
    m = re.search(r"Done.*?(?:→|->)\s*(output[/\\].+?\.mp4)", text, re.IGNORECASE)
    if m:
        return {"type": "clip_ready", "path": m.group(1)}

    # Errors / warnings
    low = text.lower()
    if "error" in low or "failed" in low or "traceback" in low:
        return {"type": "warning"}

    return {"type": "log"}


def _list_clips(job_id: str = None, newer_than: float = 0) -> list:
    clips = []
    if not OUTPUT_DIR.exists():
        return clips
        
    dirs_to_search = [OUTPUT_DIR / job_id] if job_id else [d for d in OUTPUT_DIR.iterdir() if d.is_dir()]

    for target_dir in dirs_to_search:
        # Read clips metadata if available to merge LLM analysis
        metadata_by_name = {}
        if target_dir.exists():
            metadata_file = target_dir / "clips_metadata.json"
            if metadata_file.exists():
                try:
                    import json
                    with open(metadata_file, "r", encoding="utf-8") as f:
                        meta_list = json.load(f)
                    for idx, item in enumerate(meta_list):
                        clip_num = idx + 1
                        title = item.get("title", f"clip_{clip_num:03d}")
                        safe_title = "".join(c if c.isalnum() or c in " _-" else "" for c in title)
                        safe_title = safe_title.strip().replace(" ", "_")[:40]
                        clip_filename = f"clip_{clip_num:02d}_{safe_title}.mp4"
                        metadata_by_name[clip_filename] = item
                except Exception as e:
                    logger.error(f"Failed to read clips metadata: {e}")

        if target_dir.exists():
            for f in target_dir.glob("*.mp4"):
                stat = f.stat()
                if stat.st_mtime < newer_than:
                    continue
                url_path = f"/output/{target_dir.name}/{f.name}"
                
                # Find matching metadata from clips_metadata.json
                clip_meta = metadata_by_name.get(f.name, {})
                
                clips.append({
                    "filename": f.name,
                    "size_mb":  round(stat.st_size / 1024 / 1024, 1),
                    "url":      url_path,
                    "modified": stat.st_mtime,
                    "title":    clip_meta.get("title", f.name),
                    "social_caption": clip_meta.get("social_caption", ""),
                    "reason":   clip_meta.get("reason", ""),
                    "hook_score": clip_meta.get("hook_score", "?"),
                    "viral_rating": clip_meta.get("viral_rating", None),
                    "retention_score": clip_meta.get("retention_score", None),
                    "viral_analysis": clip_meta.get("viral_analysis", ""),
                    "broll_cues": clip_meta.get("broll_cues", [])
                })
    return sorted(clips, key=lambda c: c["modified"], reverse=True)


